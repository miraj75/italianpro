function vocabTopicIds(level: BankLevel): string[] {
  return topicsOf(level).map((t) => `topic:${level}:${t.en}`);
}

export function sentenceGroupKeys(level: BankLevel): string[] {
  const tags: string[] = [];
  const seen = new Set<string>();
  for (const s of SENTENCES[level]) {
    if (!seen.has(s.grammar)) {
      seen.add(s.grammar);
      tags.push(s.grammar);
    }
  }
  return tags.slice(0, 12).map((tag) => `sent-grp:${level}:${tag}`);
}

function makeRangeIds(prefix: string, count: number): string[] {
  return Array.from({ length: count }, (_, idx) => `${prefix}-${String(idx + 1).padStart(2, '0')}`);
}

