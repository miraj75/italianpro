import type {
  AcademyDrillItem,
  AcademyExamQuestion,
  AcademyTheoryConfig,
} from './types';
import type { Tr } from '../types';

export interface A1ListeningExercise {
  id: string;
  order: number;
  category: Tr;
  title: Tr;
  audioIt: string;
  transcriptTr: Tr;
  question: Tr;
  options: Tr[];
  answer: number;
  explanation: Tr;
}

export interface A1SpeakingExercise {
  id: string;
  order: number;
  mode: 'repeat' | 'qa' | 'roleplay' | 'self-intro' | 'situation';
  modeLabel: Tr;
  prompt: Tr;
  targetIt: string;
  phoneticBn: string;
  phoneticEn: string;
  targetTr: Tr;
  tip: Tr;
}

function ls(
  id: string,
  order: number,
  catBn: string,
  catEn: string,
  tBn: string,
  tEn: string,
  audioIt: string,
  trBn: string,
  trEn: string,
  qBn: string,
  qEn: string,
  opts: [string, string][],
  answer: number,
  expBn: string,
  expEn: string,
): A1ListeningExercise {
  return {
    id,
    order,
    category: { bn: catBn, en: catEn },
    title: { bn: tBn, en: tEn },
    audioIt,
    transcriptTr: { bn: trBn, en: trEn },
    question: { bn: qBn, en: qEn },
    options: opts.map(([bn, en]) => ({ bn, en })),
    answer,
    explanation: { bn: expBn, en: expEn },
  };
}

function sp(
  id: string,
  order: number,
  mode: A1SpeakingExercise['mode'],
  modeBn: string,
  modeEn: string,
  pBn: string,
  pEn: string,
  targetIt: string,
  phoneticBn: string,
  phoneticEn: string,
  tBn: string,
  tEn: string,
  tipBn: string,
  tipEn: string,
): A1SpeakingExercise {
  return {
    id,
    order,
    mode,
    modeLabel: { bn: modeBn, en: modeEn },
    prompt: { bn: pBn, en: pEn },
    targetIt,
    phoneticBn,
    phoneticEn,
    targetTr: { bn: tBn, en: tEn },
    tip: { bn: tipBn, en: tipEn },
  };
}

