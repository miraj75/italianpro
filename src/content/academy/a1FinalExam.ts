/**
 * Generates a balanced 30-question randomized A1 Final Examination drawing across all 14 topics,
 * guaranteeing zero duplicate questions and shuffled options per attempt.
 */
export function buildA1FinalExam(rng: RandomFn = Math.random): AcademyExamQuestion[] {
  const picked: A1FinalExamQuestion[] = [];
  const usedIds = new Set<string>();

  for (const quota of TOPIC_QUOTAS) {
    const candidates = shuffleArray(
      A1_FINAL_EXAM_BANK.filter((q) => q.topic === quota.topic && !usedIds.has(q.id)),
      rng,
    ).slice(0, quota.count);
    for (const q of candidates) {
      usedIds.add(q.id);
      picked.push(q);
    }
  }

  if (picked.length < 30) {
    const remaining = shuffleArray(
      A1_FINAL_EXAM_BANK.filter((q) => !usedIds.has(q.id)),
      rng,
    ).slice(0, 30 - picked.length);
    for (const q of remaining) {
      usedIds.add(q.id);
      picked.push(q);
    }
  }

  return shuffleArray(picked, rng).map((q) => randomizeQuestionOptions(q, rng));
}
